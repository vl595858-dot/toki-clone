// Команда /help — короткая шпаргалка (полное приветствие остаётся в /start).
const { sendMessage } = require("../telegram");

const HELP_TEXT =
  "📖 Коротко, что я умею:\n\n" +
  "📝 Записать дело — напиши или надиктуй:\n" +
  "«Встреча с юристом завтра в 15:00, напомни за сутки»\n\n" +
  "🔁 Повторяющееся — добавь «каждый день / неделю / месяц / год»:\n" +
  "«Каждый понедельник в 16:00 планёрка»\n\n" +
  "📋 Посмотреть — «Что у меня сегодня», «Что завтра», «Что запланировано»\n\n" +
  "✏️ Поправить — «перенеси на пятницу», «напомни за сутки», «удали встречу с юристом»\n\n" +
  "🔕 Без напоминания — «Не напоминай про встречу»\n\n" +
  "🌦 Погода — «погода в Перми завтра вечером»\n\n" +
  "🌍 /timezone — задать город и часовой пояс\n" +
  "🗓 /calendar — все дела в удобном виде\n" +
  "👋 /start — полное приветствие с примерами";

async function handleHelp(chatId) {
  await sendMessage(chatId, HELP_TEXT);
}

module.exports = { handleHelp };
