// Команда /help — шпаргалка с примерами (приветствие — в /start).
const { sendMessage } = require("../telegram");

const HELP_TEXT =
  "📖 <b>Помощь</b>\n\n" +
  "📝 <b>Записать дело</b>: событие + дата и время (или день недели) + за сколько напомнить\n" +
  "«Встреча с юристом завтра в 15:00, напомни за сутки»\n" +
  "Можно голосом. Без времени ставлю на 12:00.\n\n" +
  "🔁 <b>Повторяющееся</b>\n" +
  "«Каждый понедельник в 16:00 планёрка»\n" +
  "Слова: каждый день / неделю / месяц / год.\n\n" +
  "📋 <b>Посмотреть</b>\n" +
  "«Что у меня сегодня», «Что завтра», «Что запланировано», «Что было вчера»\n\n" +
  "🔎 <b>Найти</b>\n" +
  "«Когда встреча с Иваном?», «Когда день рождения мамы?»\n\n" +
  "✏️ <b>Внести коррективы</b>\n" +
  "«Перенеси на пятницу», «Напомни за сутки», «Удали встречу с юристом»\n" +
  "«Не напоминай про встречу» — оставить дело без напоминания.\n\n" +
  "♾ <b>Повторяющиеся дела: кодовые слова</b>\n" +
  "Перенести все повторы — добавь слово <b>НАВСЕГДА</b>\n" +
  "«Перенеси планёрку на вторник навсегда»\n" +
  "Без этого слова переносится только одно дело.\n" +
  "Новое название — слово <b>ПЕРЕИМЕНУЙ</b>\n" +
  "«Переименуй планёрку в совещание»\n\n" +
  "🌦 <b>Погода</b> (укажи город и день)\n" +
  "«Погода в Перми завтра вечером»\n\n" +
  "🌍 <b>Часовой пояс</b> — кнопка в меню\n" +
  "🗓 <b>Календарь</b> — кнопка в меню, откроется отдельное приложение\n" +
  "👋 <b>Старт</b> — приветствие";

async function handleHelp(chatId) {
  await sendMessage(chatId, HELP_TEXT, { parseMode: "HTML" });
}

module.exports = { handleHelp };
