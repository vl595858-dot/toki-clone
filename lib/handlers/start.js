// Команда /start — короткое приветствие (подробная шпаргалка — в /help).
const { sendMessage } = require("../telegram");

const START_TEXT =
  "Привет! 👋 Я твой планировщик: запоминаю дела и вовремя напоминаю о них.\n\n" +
  "📝 <b>Как записать дело.</b> Напиши или надиктуй голосом по формуле:\n" +
  "<b>событие + дата и время (или день недели) + за сколько напомнить</b>\n" +
  "Например: «Встреча с юристом завтра в 15:00, напомни за сутки»\n" +
  "Если не скажешь, за сколько напомнить, напомню за час.\n\n" +
  "🔁 <b>Повторяющееся дело.</b> Добавь «каждую неделю» или «каждый месяц»:\n" +
  "«Каждый понедельник в 16:00 планёрка» или «Каждый месяц 5-го числа оплатить аренду».\n\n" +
  "Кнопки в меню:\n" +
  "📖 <b>Помощь</b> — шпаргалка со всеми командами, если забудешь, как что делается.\n" +
  "🌍 <b>Часовой пояс</b> — нажми и укажи свой город, чтобы напоминания приходили вовремя.\n" +
  "🗓 <b>Календарь</b> — откроется отдельное приложение, где все дела видны в удобном виде.";

async function handleStart(chatId) {
  await sendMessage(chatId, START_TEXT, { parseMode: "HTML" });
}

module.exports = { handleStart };
